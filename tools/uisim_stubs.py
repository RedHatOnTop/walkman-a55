"""Generate QML stand-ins for the app's four global context objects, for the
host UI simulator (probe/uisim).

    uisim_stubs.py MOC_JSON SCREEN_SETTINGS GLOBALS_JSON OUTDIR

Each entry of GLOBALS_JSON names a context property, the moc class it
stands for ("_class") and property values. The stub gets every property,
signal and lower-case method of that class and its in-binary bases from
MOC_JSON (mocdump.py --json). QML cannot declare upper-case methods, so
slots such as ReconfigureScreenByWindow are left out; a static render never
calls them. screenController.styleProperties comes from the "style" section
of the device's ScreenSettings.json.
"""
import json
import os
import re
import sys

QML_TYPES = {
    "bool": "bool", "int": "int", "uint": "int", "short": "int", "ushort": "int",
    "long": "int", "ulong": "int", "char": "int", "uchar": "int", "qlonglong": "real",
    "qulonglong": "real", "double": "real", "float": "real", "QString": "string",
    "QUrl": "url", "QColor": "color", "QDateTime": "date", "QDate": "date",
}
DEFAULTS = {"bool": "false", "int": "0", "real": "0", "string": '""', "url": '""',
            "color": '"transparent"', "date": "new Date()", "var": "undefined"}
IDENT = re.compile(r"[a-z_]\w*$")


def qml_type(ctype):
    return QML_TYPES.get((ctype or "").replace("const ", "").strip("&* "), "var")


def lineage(classes, name):
    by_name = {c["class"]: c for c in classes}
    chain = []
    while name in by_name:
        chain.append(by_name[name])
        name = by_name[name]["super"]
    return chain


def stub(classes, cls, values):
    chain = lineage(classes, cls)
    if not chain:
        sys.exit(f"class {cls} not in moc data")
    props, signals, funcs = {}, {}, {}
    for c in reversed(chain):
        for p in c["properties"]:
            props[p["name"]] = qml_type(p["type"])
        for m in c["methods"]:
            if m["cloned"] or not IDENT.match(m["name"]):
                continue
            args = []
            for i, a in enumerate(m["args"]):
                parts = a.rsplit(" ", 1)
                ctype, aname = (parts[0], parts[1]) if len(parts) == 2 and IDENT.match(parts[1]) else (a, f"a{i}")
                args.append((qml_type(ctype), aname))
            if m["kind"] == "signal":
                signals[m["name"]] = args
            elif m["kind"] in ("slot", "invokable"):
                funcs[m["name"]] = args

    lines = ["// Generated by tools/uisim_stubs.py from the app's moc data.",
             "import QtQuick 2.3", "", f"// {cls}", "QtObject {"]
    for name, t in props.items():
        if name in values:
            t = t if t != "var" or not isinstance(values[name], (dict, list)) else "var"
            value = json.dumps(values[name], ensure_ascii=False)
            value = f"({value})" if isinstance(values[name], dict) else value
        else:
            value = DEFAULTS[t]
        lines.append(f"    property {t} {name}: {value}")
    for name, value in values.items():
        if name not in props and not name.startswith("_"):
            lines.append(f"    property var {name}: ({json.dumps(value, ensure_ascii=False)})")
    auto = {p + "Changed" for p in props}
    for name, args in signals.items():
        if name in auto or name in props:
            continue
        lines.append(f"    signal {name}({', '.join(f'{t} {a}' for t, a in args)})")
    for name, args in funcs.items():
        if name in props or name in signals:
            continue
        lines.append(f"    function {name}({', '.join(a for _, a in args)}) {{}}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(moc_json, screen_settings, globals_json, outdir):
    classes = json.load(open(moc_json))
    style = json.load(open(screen_settings, encoding="utf-8-sig"))["TestModel"]["style"]
    spec = json.load(open(globals_json))
    spec["screenController"]["styleProperties"] = style
    os.makedirs(outdir, exist_ok=True)
    for ctx, values in spec.items():
        with open(os.path.join(outdir, ctx + ".qml"), "w") as f:
            f.write(stub(classes, values["_class"], values))
        print(f"{ctx}: {values['_class']}")


if __name__ == "__main__":
    main(*sys.argv[1:])
